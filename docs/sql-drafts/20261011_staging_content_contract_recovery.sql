begin;

create table public.curriculum (
  id bigint primary key,
  month integer not null,
  week integer not null,
  title text not null,
  url text,
  type text,
  thumbnail text,
  expert_tip text,
  check_list text[],
  equipment text[],
  steps text[],
  created_at timestamptz default now(),
  display_order integer,
  is_sub boolean not null default false,
  equipment_tag_numbers integer[]
);

create table public.spokedu_pro_programs (
  id integer generated by default as identity primary key,
  title text not null,
  video_url text,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  function_type text check (function_type is null or function_type in ('순발력','민첩성','리듬감','유연성','협응력','심폐지구력','근지구력')),
  main_theme text check (main_theme is null or main_theme in ('육상놀이체육','협동형','경쟁형','도전형','태그형')),
  group_size text check (group_size is null or group_size in ('개인','짝꿍','소그룹','대그룹')),
  checklist text,
  equipment text,
  activity_method text,
  activity_tip text,
  function_types text[],
  center_curriculum_is_sub boolean not null default false,
  source_center_curriculum_id integer references public.curriculum(id) on delete set null
);

create index idx_spokedu_pro_programs_source_center_curriculum
  on public.spokedu_pro_programs(source_center_curriculum_id);

alter table public.curriculum enable row level security;
alter table public.spokedu_pro_programs enable row level security;

-- Server routes authorize first, then use service_role for these sources.
-- Staging lacks production's private authorization helper dependency graph.
revoke all on table public.curriculum from public, anon, authenticated;
revoke all on table public.spokedu_pro_programs from public, anon, authenticated;
grant select, insert, update, delete on table public.curriculum to service_role;
grant select, insert, update, delete on table public.spokedu_pro_programs to service_role;
grant usage, select on sequence public.spokedu_pro_programs_id_seq to service_role;

commit;
