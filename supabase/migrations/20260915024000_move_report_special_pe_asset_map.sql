create table if not exists public.mr_special_pe_asset_map (
  id bigint generated by default as identity primary key,
  primary_skill text not null,
  stage text not null check (stage in ('foundation','generalize','challenge','transfer')),
  source_type text not null check (source_type in ('master','personal')),
  curriculum_id bigint references public.curriculum(id) on delete cascade,
  personal_curriculum_id bigint references public.personal_curriculum(id) on delete cascade,
  level_min smallint not null default 1 check (level_min between 1 and 5),
  level_max smallint not null default 5 check (level_max between 1 and 5 and level_max >= level_min),
  priority smallint not null default 100 check (priority > 0),
  adaptation_note text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (source_type = 'master' and curriculum_id is not null and personal_curriculum_id is null)
    or
    (source_type = 'personal' and personal_curriculum_id is not null and curriculum_id is null)
  )
);

alter table public.mr_special_pe_asset_map enable row level security;
revoke all on table public.mr_special_pe_asset_map from anon, authenticated;
grant select, insert, update, delete on table public.mr_special_pe_asset_map to service_role;

create index if not exists mr_special_pe_asset_map_skill_stage_idx
  on public.mr_special_pe_asset_map(primary_skill, stage, active, priority);

create unique index if not exists mr_special_pe_asset_map_master_uniq
  on public.mr_special_pe_asset_map(primary_skill, stage, curriculum_id)
  where source_type = 'master';
create unique index if not exists mr_special_pe_asset_map_personal_uniq
  on public.mr_special_pe_asset_map(primary_skill, stage, personal_curriculum_id)
  where source_type = 'personal';

