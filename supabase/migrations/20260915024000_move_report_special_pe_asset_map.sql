create or replace view public.mr_special_pe_asset_catalog
with (security_invoker = true)
as
select
  m.id as map_id,
  m.primary_skill,
  m.stage,
  m.source_type,
  m.level_min,
  m.level_max,
  m.priority,
  m.adaptation_note,
  m.active,
  coalesce(c.title, p.title) as title,
  coalesce(c.url, p.url) as url,
  coalesce(pm.sm_thumbnail_url, c.thumbnail, p.thumbnail) as thumbnail_url,
  coalesce(c.equipment, p.equipment) as equipment,
  case when m.source_type = 'master' then coalesce(pm.sm_theme, '놀이체육') else p.category end as source_label,
  case when m.source_type = 'master' then pm.sm_variation_method else null end as variation_method,
  c.id as curriculum_id,
  p.id as personal_curriculum_id
from public.mr_special_pe_asset_map m
left join public.curriculum c on c.id = m.curriculum_id
left join public.spokedu_master_program_meta pm on pm.curriculum_id = c.id
left join public.personal_curriculum p on p.id = m.personal_curriculum_id;

revoke all on public.mr_special_pe_asset_catalog from anon, authenticated;
grant select on public.mr_special_pe_asset_catalog to service_role;
