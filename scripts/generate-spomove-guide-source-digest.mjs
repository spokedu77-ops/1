const check = process.argv.includes('--check');

if (check) {
  if (!fs.existsSync(OUT)) {
    console.error('Generated digests missing:', OUT);
    process.exit(1);
  }
  const prev = fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (prev !== next) {
    console.error('SPOMOVE guide source digests are STALE. Run: node scripts/generate-spomove-guide-source-digest.mjs');
    process.exit(1);
  }
  console.log('OK: digests up to date');
  process.exit(0);
}

