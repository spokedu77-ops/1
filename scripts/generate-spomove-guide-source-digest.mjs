function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 16);
}

function extractSlice(src, extract) {
  const startIdx = src.indexOf(extract.start);
  if (startIdx < 0) {
    throw new Error(`Start marker not found: ${extract.start}`);
  }
  if (!extract.end) return src.slice(startIdx);
  const endIdx = src.indexOf(extract.end, startIdx + extract.start.length);
  if (endIdx < 0) {
    throw new Error(`End marker not found after start: ${extract.end}`);
  }
  return src.slice(startIdx, endIdx);
}

function digestCluster(cluster) {
  const parts = [];
  for (const rel of cluster.files) {
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) {
      throw new Error(`Missing source file for ${cluster.id}: ${rel}`);
    }
    let text = fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
    if (cluster.extracts?.length) {
      text = cluster.extracts.map((ex) => extractSlice(text, ex)).join('\n---\n');
    }
    parts.push(`${rel}\n${text}`);
  }
  return sha256(parts.join('\n====\n'));
}

function buildDigests() {
  const digests = {};
  for (const cluster of CLUSTERS) {
    digests[cluster.id] = digestCluster(cluster);
  }
  return digests;
}

function renderTs(digests) {
  const lines = [
    '/** AUTO-GENERATED by scripts/generate-spomove-guide-source-digest.mjs — do not edit. */',
    '',
    "export type SpomoveGuideSourceDigestMap = Record<string, string>;",
    '',
    'export const SPOMOVE_GUIDE_SOURCE_DIGESTS: SpomoveGuideSourceDigestMap = {',
  ];
  for (const [id, hash] of Object.entries(digests)) {
    lines.push(`  ${id}: '${hash}',`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

