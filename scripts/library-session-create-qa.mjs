import {chromium} from 'playwright';
import nextEnv from '@next/env';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {assertLocalQaTarget,isForbiddenQaRequest} from './lib/qa-network-guard.mjs';
nextEnv.loadEnvConfig(process.cwd());
const base='http://127.0.0.1:3000';
assertLocalQaTarget(base);
const output='artifacts/library-detail-v2';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const report={writes:[],errors:[],viewports:[]};
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route('**/*',route=>isForbiddenQaRequest(route.request().url())?route.abort():route.continue());
  const page=await context.newPage();
  page.on('pageerror',e=>report.errors.push(e.message));
  page.on('dialog',d=>d.accept());
  await page.goto(`${base}/login`);
  await page.locator('[name=spk-account]').fill('spm.qa.admin@spokedu.test');
  await page.locator('[name=spk-secret]').fill(process.env.SPM_QA_PASSWORD);
  await page.locator('button[type=submit]').click();
  await page.waitForURL(url=>!url.pathname.startsWith('/login'));
  const access=await(await context.request.get(`${base}/api/spokedu-master/access`)).json();
  assert(access.isAdmin && access.canUseLibrary);
  let classes=[{id:'10000000-0000-4000-8000-000000000001',name:'QA 수업반',studentIds:[],createdAt:new Date().toISOString(),updatedAt:new Date().toISOString()}];
  let sessions=[];
  let failSave=true;
  await page.route('**/api/spokedu-master/sessions',async route=>{
    if(route.request().method()==='GET') return route.fulfill({json:{data:{classes,sessions}}});
    assert.equal(route.request().method(),'POST');
    const body=route.request().postDataJSON();
    report.writes.push(body);
    if(failSave){failSave=false;return route.fulfill({status:500,json:{error:'QA simulated save failure'}});}
    assert.equal(body.status,'scheduled');
    assert.equal(body.classId,classes[0].id);
    assert.deepEqual(body.programs,[{sourceType:'program',programId:198,spomovePresetId:null}]);
    const saved={id:'20000000-0000-4000-8000-000000000001',...body,className:classes[0].name,startedAt:null,completedAt:null,attendance:[],roster:[],createdAt:new Date().toISOString(),updatedAt:new Date().toISOString(),programs:body.programs.map(p=>({...p,id:'draft-test',programTitle:'스위치 러닝 (Zone-Switch Running)',sortOrder:0,isCompleted:false}))};
    sessions=[saved];
    return route.fulfill({json:{data:saved}});
  });
  for(const width of [1440,390]){
    await page.setViewportSize({width,height:1000});
    await page.goto(`${base}/spokedu-lab/library/198`);
    await page.locator('[data-library-detail-v2]').waitFor();
    await page.evaluate(()=>document.fonts.ready);
    const header=page.locator('[data-library-detail-v2] > header');
    await header.screenshot({path:`${output}/header-refined-${width}.png`});
    const buttons=await header.locator('button').evaluateAll(list=>list.map(e=>({label:e.textContent,height:e.getBoundingClientRect().height,radius:getComputedStyle(e).borderRadius,fontSize:getComputedStyle(e).fontSize})));
    assert.equal(buttons.length,3);
    assert.equal(new Set(buttons.map(b=>b.height)).size,1);
    assert.equal(new Set(buttons.map(b=>b.radius)).size,1);
    assert.equal(new Set(buttons.map(b=>b.fontSize)).size,1);
    report.viewports.push({width,buttons});
  }
  await page.getByRole('button',{name:'내 수업에 추가',exact:true}).click();
  await page.getByRole('button',{name:'새 수업 만들기',exact:true}).waitFor();
  await page.screenshot({path:`${output}/create-entry-390.png`});
  await page.getByRole('button',{name:'새 수업 만들기',exact:true}).click();
  await page.locator('[data-session-create]').waitFor();
  assert.equal(report.writes.length,0,'Opening creation must not save');
  const dialog=page.getByRole('dialog');
  await dialog.getByText('스위치 러닝',{exact:true}).waitFor();
  await page.screenshot({path:`${output}/create-draft-390.png`});
  await dialog.getByRole('button',{name:'수업 만들기',exact:true}).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(report.writes.length,1);
  assert.equal(await page.locator('[data-session-create]').count(),1,'Failed save keeps draft open');
  await dialog.getByRole('button',{name:'수업 만들기',exact:true}).click();
  await page.getByText(/수업을 만들고 활동을 추가했습니다/).waitFor();
  assert.equal(report.writes.length,2);
  assert.deepEqual(report.writes[0],report.writes[1]);
  assert.equal(sessions[0].programs[0].isCompleted,false);
  assert.equal(sessions[0].startedAt,null);
  report.creation={prefilled:true,retryRetainsDraft:true,notCompleted:true,noImplicitStart:true,serverWrites:'intercepted; no DB mutation'};
  await page.screenshot({path:`${output}/create-success-390.png`});
  assert((await page.getByRole('link',{name:'수업 열기',exact:true}).getAttribute('href')).includes(sessions[0].id));
  // The ordinary existing-session path remains available, alongside creation.
  await page.goto(`${base}/spokedu-lab/library/198`);
  await page.getByRole('button',{name:'내 수업에 추가',exact:true}).click();
  await page.getByRole('button',{name:'새 수업 만들기',exact:true}).waitFor();
  await page.getByRole('button',{name:'새 수업 만들기',exact:true}).click();
  await page.locator('[data-session-create]').waitFor();
  await page.getByRole('dialog').getByRole('button',{name:'수업 추가 닫기',exact:true}).click();
  await page.getByRole('button',{name:'새 수업 만들기',exact:true}).waitFor();
  assert.equal(report.writes.length,2,'Cancel must not write');
  report.cancelReturnsToPicker=true;
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'새 수업 만들기',exact:true}).click();
  await page.locator('[data-session-create]').waitFor();
  const desktopDialog=page.getByRole('dialog');
  assert.equal(await desktopDialog.getAttribute('aria-modal'),'true');
  assert(await desktopDialog.getByRole('button',{name:'수업 만들기',exact:true}).isVisible());
  await page.screenshot({path:`${output}/create-draft-1440.png`});
  await desktopDialog.getByRole('button',{name:'수업 추가 닫기',exact:true}).click();
  // Empty class lists expose the existing class creator rather than a dead end.
  classes=[];sessions=[];
  await page.goto(`${base}/spokedu-lab/library/198`);
  await page.getByRole('button',{name:'내 수업에 추가',exact:true}).click();
  await page.getByRole('button',{name:'새 수업 만들기',exact:true}).click();
  await page.getByRole('button',{name:'+ 새 수업반 만들기',exact:true}).waitFor();
  assert(await page.getByRole('button',{name:'수업 만들기',exact:true}).isDisabled());
  report.noClasses={classCreationAvailable:true,sessionSaveDisabled:true};
  assert.deepEqual(report.errors,[]);
  await writeFile(`${output}/create-report.json`,JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
}finally{await browser.close();}
