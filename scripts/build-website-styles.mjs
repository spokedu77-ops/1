import fs from 'node:fs';
import path from 'node:path';
import { compile } from 'tailwindcss';
import postcss from 'postcss';

// Compile the retained design utilities with the project's Tailwind version.
// Scope the result so public design tokens cannot change Admin or LAB.
const directory = 'app/spokedu/website';
const tokens = JSON.parse(fs.readFileSync(`${directory}/styles/tokens.json`, 'utf8'));
let theme = fs.readFileSync('node_modules/tailwindcss/theme.css', 'utf8');
const declarations = [];
for (const [name, value] of Object.entries(tokens.colors)) declarations.push(`--color-${name}:${value};`);
for (const [name, [value, options]] of Object.entries(tokens.fontSize)) {
  declarations.push(`--text-${name}:${value};`, `--text-${name}--line-height:${options.lineHeight};`);
  if (options.fontWeight) declarations.push(`--text-${name}--font-weight:${Math.min(Number(options.fontWeight), 700)};`);
  if (options.letterSpacing) declarations.push(`--text-${name}--letter-spacing:-0.015em;`);
}
for (const name of Object.keys(tokens.fontFamily)) declarations.push(`--font-${name}:"Pretendard Variable",Pretendard,"Apple SD Gothic Neo","Malgun Gothic",sans-serif;`);
declarations.push('--radius-lg:2rem;', '--radius-xl:3rem;');
theme += `\n@theme {${declarations.join('\n')}}\n@tailwind utilities;`;
const sources = [];
function collect(dir) { for (const entry of fs.readdirSync(dir, { withFileTypes: true })) { const file = path.join(dir, entry.name); if (entry.isDirectory()) collect(file); else if (file.endsWith('.tsx')) sources.push(fs.readFileSync(file, 'utf8')); } }
collect(directory);
const candidates = [...new Set(sources.join('\n').match(/[a-zA-Z0-9_@!./%:[\]#(),&=+*-]+/g))];
const result = (await compile(theme)).build(candidates);
const css = postcss.parse(result);
css.walkRules(rule => {
  if (rule.parent?.type === 'atrule' && rule.parent.name.endsWith('keyframes')) return;
  if (rule.parent?.type === 'rule') return;
  if (rule.selector.includes(':root') || rule.selector.includes(':host')) rule.selector = '.website-content';
  else rule.selector = rule.selectors.map(selector => `.website-content ${selector}`).join(',\n');
});
fs.writeFileSync(`${directory}/styles/website-utilities.css`, '/* Generated by scripts/build-website-styles.mjs. Public website only. */\n' + css.toString().replaceAll('--tw-', '--website-tw-'));
